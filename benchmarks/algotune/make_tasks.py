#!/usr/bin/env python3
"""Generate MARBLE benchmark directories from AlgoTune tasks.

Usage:
  ALGOTUNE_ROOT=/path/to/AlgoTune python make_tasks.py --subset subset.txt --out tasks/

Needs the AlgoTune venv at $ALGOTUNE_ROOT/.venv (the dataset for each task is fetched once here,
not at eval time). Each generated task:
  tasks/<name>/benchmark.yaml
  tasks/<name>/repo/solver.py               editable: baseline delegates to the reference Task.solve
  tasks/<name>/repo/eval/at_eval.py         protected: evaluator (timing + is_solution checks)
  tasks/<name>/repo/eval/description.txt    protected: the task statement
  tasks/<name>/repo/eval/reference_impl.py  protected: copy of the reference task implementation (to read)
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

SOLVER = '''\
# MARBLE baseline for AlgoTune task "{task}": delegates to the reference implementation.
# The reference source is in eval/reference_impl.py (class {cls}). Replace this with a faster
# Solver.solve that returns solutions accepted by {cls}.is_solution.
from AlgoTuneTasks.{task}.{task} import {cls} as _Reference


class Solver:
    def __init__(self):
        self._ref = _Reference()

    def solve(self, problem, **kwargs):
        return self._ref.solve(problem)
'''

YAML = """\
schema_version: 1
name: {name}
description: >
  AlgoTune task "{task}". Make Solver.solve in solver.py faster than the reference
  (eval/reference_impl.py) while every output passes {cls}.is_solution. Task statement:
  eval/description.txt. Score = geometric-mean speedup over the reference across problems.
  Generated by benchmarks/algotune/make_tasks.py.
repo: repo
editable: ["solver.py", "solver_lib/**"]
protected: ["eval/**"]
env:
  PYTHONDONTWRITEBYTECODE: "1"
analyze:
  - name: cprofile
    cmd: >-
      ${{ALGOTUNE_ROOT}}/.venv/bin/python -I -m cProfile -s cumtime eval/at_eval.py --worker --impl cand
      --root ${{ALGOTUNE_ROOT}} --data {data} --task {task} --solver solver.py --n 3 --result {{out}}/prof.json
      | head -60
    timeout: 900
evaluate:
  quick:
    cmd: >-
      ${{ALGOTUNE_ROOT}}/.venv/bin/python -I eval/at_eval.py --mode quick --root ${{ALGOTUNE_ROOT}}
      --data {data} --task {task} --solver solver.py --out {{out}}
    timeout: 1800
  full:
    cmd: >-
      ${{ALGOTUNE_ROOT}}/.venv/bin/python -I eval/at_eval.py --mode full --root ${{ALGOTUNE_ROOT}}
      --data {data} --task {task} --solver solver.py --out {{out}}
    timeout: 7200
default_mode: quick
score:
  file: "{{out}}/score.json"
  key: speedup
  direction: maximize
  extra_keys: [speedup_mean, speedup_min, n_invalid, ref_time_total_s, cand_time_total_s]
correctness: {{key: correct, equals: true}}
noise:
  repeats: 3
  min_rel_improvement: 0.05
"""


def ensure_dataset(root: Path, task: str) -> Path:
    py = root / ".venv" / "bin" / "python"
    code = ("from AlgoTuner.utils.hf_datasets import ensure_hf_dataset; import sys; "
            f"p = ensure_hf_dataset({task!r}); print('MARBLE_DATA=' + str(p))")
    p = subprocess.run([str(py), "-c", code], cwd=root, capture_output=True, text=True, timeout=3600)
    line = next((l for l in p.stdout.splitlines() if l.startswith("MARBLE_DATA=")), None)
    if p.returncode != 0 or line is None or line.endswith("None"):
        raise SystemExit(f"could not fetch dataset for {task}:\n{p.stdout[-2000:]}\n{p.stderr[-2000:]}")
    base = Path(line.split("=", 1)[1])
    cand = [base / "data" / task, base / task, base]
    for c in cand:
        if list(c.glob(f"{task}_*_test.jsonl")):
            return c.resolve()
    hits = list(base.rglob(f"{task}_*_test.jsonl"))
    if not hits:
        raise SystemExit(f"dataset for {task} downloaded to {base} but no test split found")
    return hits[0].parent.resolve()


def reference_class(src: str, task: str) -> str:
    m = re.search(r'@register_task\(\s*["\']' + re.escape(task) + r'["\']\s*\)\s*\nclass\s+(\w+)', src)
    if not m:
        raise SystemExit(f"cannot find the registered Task class for {task}")
    return m.group(1)


def generate(root: Path, task: str, out: Path, force: bool) -> Path:
    tdir = root / "AlgoTuneTasks" / task
    impl = tdir / f"{task}.py"
    if not impl.exists():
        raise SystemExit(f"unknown AlgoTune task: {task}")
    name = "at-" + re.sub(r"[^a-z0-9]+", "-", task.lower()).strip("-")
    dest = out / name
    if dest.exists():
        if not force:
            print(f"skip {name} (exists; use --force)")
            return dest
        shutil.rmtree(dest)
    src = impl.read_text()
    cls = reference_class(src, task)
    data = ensure_dataset(root, task)
    try:  # keep the path portable when the data lives inside the checkout
        data_str = "${ALGOTUNE_ROOT}/" + data.relative_to(root.resolve()).as_posix()
    except ValueError:
        data_str = str(data)
    (dest / "repo" / "eval").mkdir(parents=True)
    (dest / "repo" / "solver.py").write_text(SOLVER.format(task=task, cls=cls))
    shutil.copy2(HERE / "at_eval.py", dest / "repo" / "eval" / "at_eval.py")
    shutil.copy2(impl, dest / "repo" / "eval" / "reference_impl.py")
    desc = tdir / "description.txt"
    (dest / "repo" / "eval" / "description.txt").write_text(desc.read_text() if desc.exists() else f"{task}\n")
    (dest / "benchmark.yaml").write_text(YAML.format(name=name, task=task, cls=cls, data=data_str))
    print(f"wrote {dest}  (data: {data_str})")
    return dest


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--algotune", default=os.environ.get("ALGOTUNE_ROOT"), help="AlgoTune checkout")
    ap.add_argument("--subset", help="file with one task name per line")
    ap.add_argument("--task", action="append", default=[])
    ap.add_argument("--out", default=str(HERE / "tasks"))
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    if not a.algotune:
        ap.error("set --algotune or ALGOTUNE_ROOT")
    tasks = list(a.task)
    if a.subset:
        tasks += [l.split("#", 1)[0].strip() for l in Path(a.subset).read_text().splitlines()]
    tasks = [t for t in tasks if t]
    if not tasks:
        ap.error("no tasks given")
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for t in tasks:
        generate(Path(a.algotune), t, out, a.force)
    return 0


if __name__ == "__main__":
    sys.exit(main())
