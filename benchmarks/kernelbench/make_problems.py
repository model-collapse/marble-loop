#!/usr/bin/env python3
"""Generate MARBLE benchmark directories from KernelBench problems.

Usage:
  KERNELBENCH_ROOT=/path/to/KernelBench python make_problems.py --subset subset.txt --out problems/
  python make_problems.py --kernelbench /path/to/KernelBench --problem 1:19 --problem 2:12 --out problems/

Each generated problem:
  problems/<name>/benchmark.yaml
  problems/<name>/repo/model_new.py        editable: baseline = reference with Model renamed to ModelNew
  problems/<name>/repo/eval/reference.py   protected: KernelBench reference (Model, get_inputs, ...)
  problems/<name>/repo/eval/kb_eval.py     protected: evaluator (correctness + timing via KernelBench)
  problems/<name>/repo/eval/kb_profile.py  protected: driver for nsys / ncu
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

YAML = """\
schema_version: 1
name: {name}
description: >
  KernelBench level {level} problem {pid} ({title}). Make ModelNew in model_new.py faster than the
  PyTorch reference in eval/reference.py while matching its outputs (fp32, {backend} backend).
  Score = speedup over eager PyTorch on the same GPU. Generated by benchmarks/kernelbench/make_problems.py.
repo: repo
editable: ["model_new.py", "kernels/**"]
protected: ["eval/**"]
env:
  CUDA_HOME: "${{CUDA_HOME:-/usr/local/cuda}}"
  # ninja (torch extension builds) lives in the KernelBench venv; nvcc in CUDA_HOME/bin
  PATH: "${{KERNELBENCH_ROOT}}/.venv/bin:${{CUDA_HOME:-/usr/local/cuda}}/bin:${{PATH}}"
  TORCH_EXTENSIONS_DIR: "{{out}}/torch_extensions"
  TRITON_CACHE_DIR: "{{out}}/triton_cache"
  PYTHONDONTWRITEBYTECODE: "1"
analyze:
  - name: nsys
    cmd: >-
      ${{CUDA_HOME:-/usr/local/cuda}}/bin/nsys profile -o {{out}}/nsys --force-overwrite true --stats=true
      ${{KERNELBENCH_ROOT}}/.venv/bin/python eval/kb_profile.py --ref eval/reference.py --kernel model_new.py
    timeout: 600
    resources: {{gpu: 1}}
  - name: ncu
    cmd: >-
      ${{CUDA_HOME:-/usr/local/cuda}}/bin/ncu --section SpeedOfLight --section Occupancy
      --section MemoryWorkloadAnalysis --launch-skip 20 --launch-count 10
      ${{KERNELBENCH_ROOT}}/.venv/bin/python eval/kb_profile.py --ref eval/reference.py --kernel model_new.py --iters 5
    timeout: 900
    resources: {{gpu: 1}}
evaluate:
  quick:
    cmd: >-
      ${{KERNELBENCH_ROOT}}/.venv/bin/python eval/kb_eval.py --mode quick --backend {backend}
      --ref eval/reference.py --kernel model_new.py --out {{out}}
    timeout: 900
    resources: {{gpu: 1}}
  full:
    cmd: >-
      ${{KERNELBENCH_ROOT}}/.venv/bin/python eval/kb_eval.py --mode full --backend {backend}
      --ref eval/reference.py --kernel model_new.py --out {{out}}
    timeout: 1800
    resources: {{gpu: 1}}
  reference:
    # Calibration only: times the unmodified pure-PyTorch baseline, which has no custom kernel and
    # therefore fails KernelBench's static check. MARBLE refuses to score candidates in this mode.
    cmd: >-
      ${{KERNELBENCH_ROOT}}/.venv/bin/python eval/kb_eval.py --mode quick --backend {backend} --no-static-check
      --ref eval/reference.py --kernel model_new.py --out {{out}}
    timeout: 900
    resources: {{gpu: 1}}
    calibration_only: true
default_mode: quick
score:
  file: "{{out}}/score.json"
  key: speedup
  direction: maximize
  extra_keys: [runtime, ref_eager, kb_speedup, speedup_vs_compile, excessive_speedup, static_warnings]
correctness: {{key: correct, equals: true}}
noise:
  repeats: 3
  min_rel_improvement: 0.03
"""


def find_problem(root: Path, level: int, pid: int) -> Path:
    d = root / "KernelBench" / f"level{level}"
    hits = [p for p in d.glob(f"{pid}_*.py")]
    if len(hits) != 1:
        raise SystemExit(f"problem level {level} id {pid}: expected 1 file in {d}, found {len(hits)}")
    return hits[0]


def baseline_from_reference(src: str) -> str:
    """Rename the reference Model class to ModelNew (keeps behaviour identical)."""
    if not re.search(r"^class Model\(", src, re.M):
        raise ValueError("reference has no top-level 'class Model('")
    out = re.sub(r"^class Model\(", "class ModelNew(", src, flags=re.M)
    out = re.sub(r"\bsuper\(Model,", "super(ModelNew,", out)
    header = ("# MARBLE baseline: the KernelBench reference with Model renamed to ModelNew.\n"
              "# Replace the PyTorch ops with custom kernels to make it faster.\n")
    return header + out


def slug(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "-", name).strip("-").lower()[:40]


def generate(root: Path, level: int, pid: int, out: Path, backend: str, force: bool) -> Path:
    src_file = find_problem(root, level, pid)
    title = src_file.stem.split("_", 1)[1].strip("_")
    name = f"kb-l{level}-{pid:03d}-{slug(title)}"
    dest = out / name
    if dest.exists():
        if not force:
            print(f"skip {name} (exists; use --force)")
            return dest
        shutil.rmtree(dest)
    (dest / "repo" / "eval").mkdir(parents=True)
    ref = src_file.read_text()
    (dest / "repo" / "eval" / "reference.py").write_text(ref)
    (dest / "repo" / "model_new.py").write_text(baseline_from_reference(ref))
    shutil.copy2(HERE / "kb_eval.py", dest / "repo" / "eval" / "kb_eval.py")
    shutil.copy2(HERE / "kb_profile.py", dest / "repo" / "eval" / "kb_profile.py")
    (dest / "benchmark.yaml").write_text(YAML.format(name=name, level=level, pid=pid, title=title, backend=backend))
    print(f"wrote {dest}")
    return dest


def parse_ids(items: list[str]) -> list[tuple[int, int]]:
    ids = []
    for it in items:
        it = it.split("#", 1)[0].strip()
        if not it:
            continue
        lvl, pid = it.split(":")
        ids.append((int(lvl), int(pid)))
    return ids


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--kernelbench", default=os.environ.get("KERNELBENCH_ROOT"), help="KernelBench checkout")
    ap.add_argument("--subset", help="file with level:id lines")
    ap.add_argument("--problem", action="append", default=[], help="level:id (repeatable)")
    ap.add_argument("--out", default=str(HERE / "problems"))
    ap.add_argument("--backend", default="cuda", choices=["cuda", "triton"])
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    if not a.kernelbench:
        ap.error("set --kernelbench or KERNELBENCH_ROOT")
    items = list(a.problem)
    if a.subset:
        items += Path(a.subset).read_text().splitlines()
    ids = parse_ids(items)
    if not ids:
        ap.error("no problems given (--subset or --problem)")
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for lvl, pid in ids:
        generate(Path(a.kernelbench), lvl, pid, out, a.backend, a.force)
    return 0


if __name__ == "__main__":
    sys.exit(main())
